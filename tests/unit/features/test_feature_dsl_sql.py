@pytest.fixture
def dsl_test_cases():
    """Load test cases from fixtures/dsl_test_cases.json"""
    fixtures_dir = Path(__file__).parent.parent.parent / "fixtures"
    test_cases_file = fixtures_dir / "dsl_test_cases.json"

    if not test_cases_file.exists():
        pytest.skip(f"Test cases file not found: {test_cases_file}")

    with open(test_cases_file, 'r') as f:
        return json.load(f)


def test_all_dsl_cases_compile(dsl_test_cases):
    """
    Test that all DSL cases in fixtures/dsl_test_cases.json compile successfully.

    This ensures that the comprehensive test suite generated by Claude/Brain
    covers all supported DSL operations and patterns.
    """
    failed_cases = []

    for case in dsl_test_cases:
        name = case.get("name", "unnamed")
        dsl = case.get("dsl")

        if not dsl:
            failed_cases.append((name, "Missing DSL spec"))
            continue

        try:
            sql = dsl_to_sql(dsl)
            # Basic sanity check - SQL should not be empty
            assert sql and len(sql) > 0, f"Empty SQL for case: {name}"
        except FeatureDSLCompileError as e:
            failed_cases.append((name, f"Compile error: {e}"))
        except Exception as e:
            failed_cases.append((name, f"Unexpected error: {e}"))

    if failed_cases:
        error_msg = "\n".join([f"  - {name}: {error}" for name, error in failed_cases])
        pytest.fail(f"Failed to compile {len(failed_cases)}/{len(dsl_test_cases)} cases:\n{error_msg}")


