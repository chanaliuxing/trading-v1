def test_ratio_generates_nullsafe_division() -> None:
    spec = {"op": "ratio", "num": "f.ret_5", "den": "f.atr_14", "eps": 1e-6}
    sql = dsl_to_sql(spec)
    assert "f.ret_5" in sql
    assert "f.atr_14" in sql
    assert "nullIf" in sql


def test_nested_abs_in_ratio() -> None:
    spec = {
        "op": "ratio",
        "num": "f.ret_5",
        "den": {"op": "abs", "col": "f.atr_14"},
    }
    sql = dsl_to_sql(spec)
    # Ensure nested abs compiled and wrapped inside nullIf
    assert "abs(f.atr_14)" in sql
    assert "nullIf(" in sql


